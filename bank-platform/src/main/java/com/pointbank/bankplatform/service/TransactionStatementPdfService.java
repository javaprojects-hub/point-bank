package com.pointbank.bankplatform.service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;

import com.pointbank.bankplatform.constant.AccountTransactionStatus;
import com.pointbank.bankplatform.constant.AccountType;
import com.pointbank.bankplatform.dto.AccountResponse;
import com.pointbank.bankplatform.dto.AccountTransactionResponse;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.springframework.stereotype.Service;

@Service
public class TransactionStatementPdfService {

    private static final float LEFT_MARGIN = 42;
    private static final float TOP_MARGIN = 750;
    private static final float BOTTOM_MARGIN = 48;
    private static final float LINE_HEIGHT = 15;
    private static final DateTimeFormatter TIMESTAMP_FORMAT =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss 'UTC'").withZone(ZoneOffset.UTC);

    public byte[] generate(
            AccountResponse account,
            int year,
            Integer fromMonth,
            Integer toMonth,
            AccountType accountTypeFilter,
            AccountTransactionStatus statusFilter,
            List<AccountTransactionResponse> transactions
    ) throws IOException {
        try (PDDocument document = new PDDocument(); ByteArrayOutputStream output = new ByteArrayOutputStream()) {
            List<String> lines = statementLines(
                    account, year, fromMonth, toMonth, accountTypeFilter, statusFilter, transactions
            );
            PDPage page = new PDPage(PDRectangle.A4);
            document.addPage(page);
            PDPageContentStream content = new PDPageContentStream(document, page);
            float y = TOP_MARGIN;
            try {
                for (String line : lines) {
                    if (y < BOTTOM_MARGIN) {
                        content.close();
                        page = new PDPage(PDRectangle.A4);
                        document.addPage(page);
                        content = new PDPageContentStream(document, page);
                        y = TOP_MARGIN;
                    }
                    writeLine(content, line, y);
                    y -= LINE_HEIGHT;
                }
            } finally {
                content.close();
            }
            document.save(output);
            return output.toByteArray();
        }
    }

    private List<String> statementLines(
            AccountResponse account,
            int year,
            Integer fromMonth,
            Integer toMonth,
            AccountType accountTypeFilter,
            AccountTransactionStatus statusFilter,
            List<AccountTransactionResponse> transactions
    ) {
        List<String> lines = new ArrayList<>();
        lines.add("POINTBANK - ACCOUNT TRANSACTION STATEMENT");
        lines.add("Account number: " + account.accountNumber());
        lines.add("Account type: " + account.accountType()
                + (accountTypeFilter == null ? "" : " (filter: " + accountTypeFilter + ")")
                + "    Currency: " + account.currencyCode());
        lines.add("Period: " + (fromMonth == null
                ? String.valueOf(year)
                : String.format("%04d-%02d to %04d-%02d", year, fromMonth, year, toMonth)));
        lines.add("Transaction status filter: " + (statusFilter == null ? "ALL" : statusFilter));
        lines.add("Transactions: " + transactions.size());
        lines.add("");
        lines.add("UTC TIMESTAMP       | REFERENCE                            | TYPE | STATUS    | AMOUNT       | AVAILABLE AFTER");
        lines.add("-------------------------------------------------------------------------------------------------------");
        for (AccountTransactionResponse transaction : transactions) {
            lines.add(String.format(
                    "%s | %s | %-3s | %-9s | %s %12s | %s %12s",
                    TIMESTAMP_FORMAT.format(transaction.createdAt()),
                    transaction.transactionReference(),
                    transaction.transactionType(),
                    transaction.status(),
                    transaction.currencyCode(),
                    transaction.amount().toPlainString(),
                    transaction.currencyCode(),
                    transaction.availableBalanceAfter().toPlainString()
            ));
        }
        if (transactions.isEmpty()) {
            lines.add("No transactions match the selected period and filters.");
        }
        lines.add("");
        lines.add("Generated by PointBank. This statement contains posted and non-posted transaction records.");
        return lines;
    }

    private void writeLine(PDPageContentStream content, String line, float y) throws IOException {
        String printableLine = line.replaceAll("[^\\x20-\\x7E]", "?");
        content.beginText();
        content.setFont(new PDType1Font(Standard14Fonts.FontName.COURIER), 6.5f);
        content.newLineAtOffset(LEFT_MARGIN, y);
        content.showText(printableLine);
        content.endText();
    }

}
